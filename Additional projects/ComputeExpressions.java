/* 1.3 module computing expressions.
This module represents how java handles computing expressions in the form of strings.
The JVM does not require the user to input "" when working with numbers.
*/
// method
public class ComputeExpressions {
    // class
    public static void main(String[] args) {
        System.out.println("(11 + 2 * 3) / (45 - 3.5) =");
        System.out.println((11 + 2 * 3) / (45 - 3.5));
    }
}
