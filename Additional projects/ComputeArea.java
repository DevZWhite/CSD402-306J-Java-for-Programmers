public class ComputeArea {
    public static void main(String[] args) {
        double radius;
        double area;
        // assign a radius
        radius = 2;
        // compute area
        area = radius * radius * 3.14159;
        //display results
        System.out.println("The area for the circle of radius" + " "
         + radius + " " + "is" + " " + area);
    }
    
}
